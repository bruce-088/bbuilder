import type { MyaPdfArgs } from "./myaPdfGenerator";

/**
 * Markdown twin of the PDF renderer. Same payload (`MyaPdfArgs`) in, clean
 * Markdown out — so every document Mya generates can be downloaded as either
 * a PDF or a verbatim .md file with zero content divergence.
 */

function sanitizeMarkdownFilename(name: string): string {
  const base = (name || "mya-document")
    .toLowerCase()
    .replace(/\.(md|pdf|markdown)$/i, "")
    .replace(/[^a-z0-9-_]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
  return `${base || "mya-document"}.md`;
}

export function buildMyaMarkdown(args: MyaPdfArgs): string {
  const lines: string[] = [];
  lines.push(`# ${(args.title || "Untitled").trim()}`);
  if (args.subtitle?.trim()) {
    lines.push("", `> ${args.subtitle.trim()}`);
  }

  for (const section of args.sections || []) {
    const body = (section.body || "").replace(/\r\n/g, "\n").trim();
    if (section.heading?.trim()) {
      lines.push("", `## ${section.heading.trim()}`);
    }
    if (body) lines.push("", body);
  }

  const date = new Date().toLocaleDateString(undefined, {
    year: "numeric",
    month: "short",
    day: "numeric",
  });
  lines.push("", "---", "", `_Generated by Mya · ${date}_`, "");

  return lines.join("\n");
}

export function downloadMyaMarkdown(args: MyaPdfArgs): string {
  const markdown = buildMyaMarkdown(args);
  const filename = sanitizeMarkdownFilename(args.filename || args.title || "mya-document");
  const blob = new Blob([markdown], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 4000);
  return filename;
}
