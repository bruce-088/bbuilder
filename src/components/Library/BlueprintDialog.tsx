import { useEffect, useState } from "react";
import { supabase } from "@/integrations/supabase/client";
import { Dialog, DialogContent, DialogHeader, DialogTitle, DialogDescription } from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { ScrollArea } from "@/components/ui/scroll-area";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { Loader2, Send, ExternalLink, Copy } from "lucide-react";
import { toast } from "sonner";
import { BLUEPRINT_SECTIONS, type SystemBlueprint } from "@/lib/blueprintSchema";
import { ACTIVE_HANDOFF_TARGET, buildHandoffPackage, serializeHandoff } from "@/lib/handoff";

interface Props {
  blueprintId: string | null;
  open: boolean;
  onOpenChange: (open: boolean) => void;
}

export default function BlueprintDialog({ blueprintId, open, onOpenChange }: Props) {
  const [b, setB] = useState<SystemBlueprint | null>(null);
  const [loading, setLoading] = useState(false);
  const [sending, setSending] = useState(false);

  useEffect(() => {
    if (!blueprintId || !open) return;
    setLoading(true);
    supabase
      .from("system_blueprints" as any)
      .select("*")
      .eq("id", blueprintId)
      .single()
      .then(({ data, error }) => {
        if (error) toast.error(error.message);
        setB((data as unknown as SystemBlueprint) || null);
        setLoading(false);
      });
  }, [blueprintId, open]);

  const handoff = async () => {
    if (!b) return;
    setSending(true);
    const pkg = buildHandoffPackage(b);
    const res = await ACTIVE_HANDOFF_TARGET.deliver(pkg);
    setSending(false);
    res.ok ? toast.success(res.message) : toast.error(res.message);
  };

  const copyJson = () => {
    if (!b) return;
    navigator.clipboard.writeText(JSON.stringify(b.blueprint, null, 2));
    toast.success("Blueprint JSON copied");
  };

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-w-4xl max-h-[90vh] overflow-hidden flex flex-col">
        {loading || !b ? (
          <div className="flex items-center justify-center py-20"><Loader2 className="w-6 h-6 animate-spin text-muted-foreground" /></div>
        ) : (
          <>
            <DialogHeader>
              <DialogTitle className="flex items-center gap-2">{b.title}</DialogTitle>
              <DialogDescription>
                {b.summary || "Systems blueprint generated by Mya."}
              </DialogDescription>
              <div className="flex items-center gap-1.5 flex-wrap pt-2">
                <Badge variant="outline" className="text-[10px]">{b.source_type}</Badge>
                {b.facets?.revenue_model && <Badge variant="secondary" className="text-[10px]">{String(b.facets.revenue_model)}</Badge>}
                {typeof b.facets?.automation_potential === "number" && (
                  <Badge variant="secondary" className="text-[10px]">🤖 {b.facets.automation_potential}% automatable</Badge>
                )}
                {typeof b.facets?.startup_cost_usd === "number" && (
                  <Badge variant="secondary" className="text-[10px]">💵 ${b.facets.startup_cost_usd} startup</Badge>
                )}
                {b.tags.map((t) => <Badge key={t} variant="outline" className="text-[10px]">{t}</Badge>)}
              </div>
            </DialogHeader>

            <Tabs defaultValue="blueprint" className="flex-1 overflow-hidden flex flex-col">
              <TabsList className="self-start">
                <TabsTrigger value="blueprint">Blueprint</TabsTrigger>
                <TabsTrigger value="mutation">Mutation Logic</TabsTrigger>
                <TabsTrigger value="handoff">OpenClaw Handoff</TabsTrigger>
                <TabsTrigger value="raw">Raw JSON</TabsTrigger>
              </TabsList>

              <TabsContent value="blueprint" className="flex-1 overflow-hidden mt-3">
                <ScrollArea className="h-[55vh] pr-3">
                  <div className="space-y-5">
                    {BLUEPRINT_SECTIONS.map((s) => {
                      const body = b.blueprint?.[s.id];
                      if (!body) return null;
                      return (
                        <section key={s.id}>
                          <h3 className="text-sm font-semibold text-emerald-400 mb-1">{s.label}</h3>
                          <div className="text-sm text-foreground/90 whitespace-pre-wrap leading-relaxed">{body}</div>
                        </section>
                      );
                    })}
                    {Object.keys(b.blueprint || {}).filter((k) => !BLUEPRINT_SECTIONS.find((s) => s.id === k)).map((k) => (
                      <section key={k}>
                        <h3 className="text-sm font-semibold text-emerald-400 mb-1 capitalize">{k.replace(/_/g, " ")}</h3>
                        <div className="text-sm text-foreground/90 whitespace-pre-wrap leading-relaxed">{String(b.blueprint[k])}</div>
                      </section>
                    ))}
                  </div>
                </ScrollArea>
              </TabsContent>

              <TabsContent value="mutation" className="flex-1 overflow-hidden mt-3">
                <ScrollArea className="h-[55vh] pr-3">
                  <p className="text-xs text-muted-foreground mb-3">Workspace state transitions — not files to create. This is how the business gets stood up.</p>
                  <ol className="space-y-2">
                    {buildHandoffPackage(b).mutation_pipeline.map((step, i) => (
                      <li key={step.state} className="flex items-start gap-3 p-2 rounded border border-border/40 bg-card/30">
                        <div className="w-6 h-6 rounded-full bg-emerald-500/20 text-emerald-400 flex items-center justify-center text-xs font-bold flex-shrink-0">{i + 1}</div>
                        <div className="flex-1">
                          <div className="text-sm font-medium">{step.label}</div>
                          <div className="text-xs text-muted-foreground">state: <code>{step.state}</code> → {step.agent}</div>
                        </div>
                      </li>
                    ))}
                  </ol>
                </ScrollArea>
              </TabsContent>

              <TabsContent value="handoff" className="flex-1 overflow-hidden mt-3">
                <ScrollArea className="h-[55vh] pr-3">
                  <pre className="text-[11px] bg-muted/30 p-3 rounded whitespace-pre-wrap break-words">
                    {serializeHandoff(buildHandoffPackage(b))}
                  </pre>
                </ScrollArea>
              </TabsContent>

              <TabsContent value="raw" className="flex-1 overflow-hidden mt-3">
                <ScrollArea className="h-[55vh] pr-3">
                  <pre className="text-[11px] bg-muted/30 p-3 rounded whitespace-pre-wrap break-words">
                    {JSON.stringify(b.blueprint, null, 2)}
                  </pre>
                </ScrollArea>
              </TabsContent>
            </Tabs>

            <div className="flex items-center gap-2 pt-3 border-t border-border/50">
              <Button onClick={handoff} disabled={sending} className="bg-emerald-500 hover:bg-emerald-600 text-white">
                <Send className="w-4 h-4 mr-1.5" />
                {sending ? "Sending..." : "Handoff to OpenClaw"}
              </Button>
              <Button variant="outline" size="sm" onClick={copyJson}>
                <Copy className="w-4 h-4 mr-1.5" /> Copy JSON
              </Button>
              {b.source_url && (
                <Button variant="ghost" size="sm" asChild>
                  <a href={b.source_url} target="_blank" rel="noreferrer">
                    <ExternalLink className="w-4 h-4 mr-1.5" /> Source
                  </a>
                </Button>
              )}
              <div className="ml-auto text-[10px] text-muted-foreground">
                target: <code>{ACTIVE_HANDOFF_TARGET.id}</code>
              </div>
            </div>
          </>
        )}
      </DialogContent>
    </Dialog>
  );
}
